"""
Writes a short human-readable summary of MLflow's tracked training runs to
docs/EXPERIMENT_LOG.md: the best run so far (its hyperparameters + validation
MAE) and how many runs exist in total. Called automatically at the end of
every train_model() run (see train.py) so the doc updates exactly when
there's something new to report -- not on a schedule.

"Runs" here means every training attempt this project has ever logged,
tuning sweeps included -- mlflow.search_runs() returns every nested run
(each individual Optuna trial, plus final/winning retrains), not just the
final saved-checkpoint ones.

Run standalone too, to regenerate the doc without training:
    python -m backend.models.experiment_log
"""

import datetime as dt
from pathlib import Path

import mlflow

from backend.models.train import EXPERIMENT_NAME, _configure_mlflow

DOCS_PATH = Path(__file__).parent.parent.parent / "docs" / "EXPERIMENT_LOG.md"


def write_experiment_log() -> None:
    _configure_mlflow()
    runs = mlflow.search_runs(experiment_names=[EXPERIMENT_NAME])
    scored = runs.dropna(subset=["metrics.best_val_mae_s"]) if "metrics.best_val_mae_s" in runs.columns else runs.iloc[0:0]

    DOCS_PATH.parent.mkdir(parents=True, exist_ok=True)

    if scored.empty:
        DOCS_PATH.write_text("# Experiment Log\n\nNo MLflow runs recorded yet.\n", encoding="utf-8")
        print(f"Wrote {DOCS_PATH} (no scored runs yet)")
        return

    best = scored.loc[scored["metrics.best_val_mae_s"].idxmin()]
    lines = [
        "# Experiment Log",
        "",
        f"_Last updated: {dt.datetime.now(dt.timezone.utc).strftime('%Y-%m-%d %H:%M UTC')} — {len(runs)} run(s) total._",
        "",
        "## Best run so far",
        "",
        f"- Run: `{best.get('tags.mlflow.runName') or best['run_id']}` ({best.get('tags.run_type', 'n/a')})",
        f"- Validation MAE: {best['metrics.best_val_mae_s']:.3f}s",
        f"- Hidden sizes: {best.get('params.hidden_sizes', 'n/a')}",
        f"- Dropout: {best.get('params.dropout', 'n/a')}",
        f"- Learning rate: {best.get('params.learning_rate', 'n/a')}",
        f"- Batch size: {best.get('params.batch_size', 'n/a')}",
        f"- Weight decay: {best.get('params.weight_decay', 'n/a')}",
        "",
        "View the full run history: `cd f1-race-analytics && mlflow ui`.",
        "",
        "Auto-generated by `backend/models/experiment_log.py`, called at the end of every `train_model()` run -- see backend/models/train.py.",
    ]
    DOCS_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {DOCS_PATH}")


if __name__ == "__main__":
    write_experiment_log()
